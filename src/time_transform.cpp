int Calendar2MJD(const int& year, const int& month, const int& day, const double& day_fraction, double& MJD)
{
	//借助IAU SOFA
	double MJD0;
	int b = iauCal2jd(year, month, day, &MJD0, &MJD);
	MJD += day_fraction;//整天+天的小数部分

	return b;//返回sofa函数相同的值，方便排查
}

/*
 * 日历时间转换为修正儒略日（年月日时分秒版本）
 */
int Calendar2MJD(const int& year, const int& month, const int& day, const int& hour, const int& minute, const double& second, double& MJD)
{
	/*
	 * 功能：将年月日时分秒转换为修正儒略日
	 *
	 * 参数说明：
	 * @param year   年份
	 * @param month  月份 (1-12)
	 * @param day    日期 (1-31)
	 * @param hour   小时 (0-23，24小时制)
	 * @param minute 分钟 (0-59)
	 * @param second 秒（包含小数秒，0-59.999...）
	 * @param MJD    输出的修正儒略日
	 * @return       IAU SOFA函数返回值（用于错误检查）
	 *
	 * 转换原理：
	 * 1. 将时分秒转换为日的小数部分
	 * 2. 调用原有的Calendar2MJD函数完成转换
	 *
	 * 时间转换公式：
	 * day_fraction = hour/24 + minute/1440 + second/86400
	 * 说明：1天 = 24小时 = 1440分钟 = 86400秒
	 *
	 * 使用示例：
	 * double mjd;
	 * int status = Calendar2MJD(2024, 1, 1, 12, 30, 45.5, mjd);
	 * // 将2024年1月1日12:30:45.5转换为MJD
	 *
	 * 精度说明：
	 * - 支持微秒级别的时间精度
	 * - second参数可以包含小数部分
	 * - 最终精度取决于double类型的精度限制
	 */

	// 第一步：将时分秒转换为日的小数部分
	// hour/24.0：小时转换为日的小数部分
	// minute/1440.0：分钟转换为日的小数部分 (1440 = 24 * 60)
	// second/86400.0：秒转换为日的小数部分 (86400 = 24 * 60 * 60)
	double day_fraction = hour / 24.0 + minute / 1440.0 + second / 86400.0;

	// 第二步：调用原有的Calendar2MJD函数进行转换
	// 利用函数重载，编译器会根据参数选择对应的版本
	return Calendar2MJD(year, month, day, day_fraction, MJD);
}

int Calendar2JD(const int& year, const int& month, const int& day, const double& day_fraction, double& JD)
{
	//借助IAU SOFA
	double MJD0;
	int b = iauCal2jd(year, month, day, &MJD0, &JD);
	JD += MJD0 + day_fraction;//整天+天的小数部分

	return b;//返回sofa函数相同的值，方便排查
}

/*
 * 日历时间转换为儒略日（年月日时分秒版本）
 */
int Calendar2JD(const int& year, const int& month, const int& day, const int& hour, const int& minute, const double& second, double& JD)
{
	/*
	 * 功能：将年月日时分秒转换为儒略日
	 *
	 * 参数说明：
	 * @param year   年份
	 * @param month  月份 (1-12)
	 * @param day    日期 (1-31)
	 * @param hour   小时 (0-23，24小时制)
	 * @param minute 分钟 (0-59)
	 * @param second 秒（包含小数秒，0-59.999...）
	 * @param JD     输出的儒略日
	 * @return       IAU SOFA函数返回值（用于错误检查）
	 *
	 * 转换原理：
	 * 1. 将时分秒转换为日的小数部分
	 * 2. 调用原有的Calendar2JD函数完成转换
	 *
	 * 时间转换公式：
	 * day_fraction = hour/24 + minute/1440 + second/86400
	 * 说明：1天 = 24小时 = 1440分钟 = 86400秒
	 *
	 * JD与MJD的关系：
	 * JD = MJD + 2400000.5
	 * JD：儒略日（从公元前4713年1月1日12时开始）
	 * MJD：修正儒略日（从1858年11月17日0时开始）
	 *
	 * 使用示例：
	 * double jd;
	 * int status = Calendar2JD(2024, 1, 1, 12, 30, 45.5, jd);
	 * // 将2024年1月1日12:30:45.5转换为JD
	 *
	 * 精度说明：
	 * - 支持微秒级别的时间精度
	 * - second参数可以包含小数部分
	 * - 最终精度取决于double类型的精度限制
	 */

	// 第一步：将时分秒转换为日的小数部分
	// hour/24.0：小时转换为日的小数部分
	// minute/1440.0：分钟转换为日的小数部分 (1440 = 24 * 60)
	// second/86400.0：秒转换为日的小数部分 (86400 = 24 * 60 * 60)
	double day_fraction = hour / 24.0 + minute / 1440.0 + second / 86400.0;

	// 第二步：调用原有的Calendar2JD函数进行转换
	// 利用函数重载，编译器会根据参数选择对应的版本
	return Calendar2JD(year, month, day, day_fraction, JD);
}

int MJD2Calendar(const double& MJD, int& year, int& month, int& day, int& hour, int& minute, double& second)
{
	double day_fraction;

	int b = iauJd2cal(2400000.5, MJD, &year, &month, &day, &day_fraction);
	//提取时分秒
	double total_seconds = day_fraction * 86400.0; //一天86400秒
	hour = static_cast<int>(total_seconds / 3600);
	total_seconds -= hour * 3600;
	minute = static_cast<int>(total_seconds / 60);
	total_seconds -= minute * 60;
	second = total_seconds;

	return b;
}

