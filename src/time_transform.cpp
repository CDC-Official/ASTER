double TT2UTC(double MJD_TT)
{
	// 与 UTC2TT 相同，避免完整 JD 的大数加减损失时间分辨率。
	//GET TAI
	double JD1_TAI, JD2_TAI;
	double JD1_UTC, JD2_UTC;
	int a = iauTttai(START_OF_MJD, MJD_TT, &JD1_TAI, &JD2_TAI);
	a = iauTaiutc(JD1_TAI, JD2_TAI, &JD1_UTC, &JD2_UTC);
	double MJD_UTC = (JD1_UTC - START_OF_MJD) + JD2_UTC;
	return MJD_UTC;
}


double TT2TCG(double MJD_TT)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Terrestrial Time (TT) to Geocentric Coordinate Time (TCG).
	 * - Input:
	 *   MJD_TT is TT expressed as one Modified Julian Date number.
	 * - Output:
	 *   The returned value is TCG expressed as one Modified Julian Date number.
	 * - Method:
	 *   This is a thin wrapper around SOFA iauTttcg. SOFA uses two-part
	 *   Julian Dates for numerical precision; CDC_lib usually passes epochs
	 *   as one MJD, so this function hides the SOFA two-part interface.
	 */

	// SOFA expects Julian Date, so add the MJD zero point before calling it.
	double JD1_TCG, JD2_TCG;
	iauTttcg(START_OF_MJD + MJD_TT, 0.0, &JD1_TCG, &JD2_TCG);

	// SOFA returns a two-part JD. Add the parts and convert back to MJD.
	return JD1_TCG + JD2_TCG - START_OF_MJD;
}

double TCG2TT(double MJD_TCG)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Geocentric Coordinate Time (TCG) back to Terrestrial Time (TT).
	 * - Input:
	 *   MJD_TCG is TCG expressed as one Modified Julian Date number.
	 * - Output:
	 *   The returned value is TT expressed as one Modified Julian Date number.
	 * - Method:
	 *   This is a thin wrapper around SOFA iauTcgtt and is the inverse of
	 *   TT2TCG, apart from normal double-precision roundoff.
	 */

	// Convert the input MJD to the JD form expected by SOFA.
	double JD1_TT, JD2_TT;
	iauTcgtt(START_OF_MJD + MJD_TCG, 0.0, &JD1_TT, &JD2_TT);

	// Merge SOFA's two-part JD result and return to the project's MJD convention.
	return JD1_TT + JD2_TT - START_OF_MJD;
}

double TDB2TCB(double MJD_TDB)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Barycentric Dynamical Time (TDB) to Barycentric Coordinate
	 *   Time (TCB).
	 * - Input:
	 *   MJD_TDB is TDB expressed as one Modified Julian Date number.
	 * - Output:
	 *   The returned value is TCB expressed as one Modified Julian Date number.
	 * - Method:
	 *   This is a thin wrapper around SOFA iauTdbtcb. It applies the IAU
	 *   linear relationship between TDB and TCB.
	 */

	// Convert project MJD to JD before calling the SOFA time-scale routine.
	double JD1_TCB, JD2_TCB;
	iauTdbtcb(START_OF_MJD + MJD_TDB, 0.0, &JD1_TCB, &JD2_TCB);

	// Convert SOFA's two-part JD output back to a single MJD.
	return JD1_TCB + JD2_TCB - START_OF_MJD;
}

double TCB2TDB(double MJD_TCB)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Barycentric Coordinate Time (TCB) back to Barycentric Dynamical
	 *   Time (TDB).
	 * - Input:
	 *   MJD_TCB is TCB expressed as one Modified Julian Date number.
	 * - Output:
	 *   The returned value is TDB expressed as one Modified Julian Date number.
	 * - Method:
	 *   This is a thin wrapper around SOFA iauTcbtdb and is the inverse of
	 *   TDB2TCB, apart from normal double-precision roundoff.
	 * - Practical use:
	 *   This wrapper is useful before reading a JPL planetary ephemeris if only TCB is known,
	 *   because JPL DE files are normally evaluated using a TDB-like epoch.
	 */

	// Convert project MJD to JD before calling the SOFA time-scale routine.
	double JD1_TDB, JD2_TDB;
	iauTcbtdb(START_OF_MJD + MJD_TCB, 0.0, &JD1_TDB, &JD2_TDB);

	// Convert SOFA's two-part JD output back to a single MJD.
	return JD1_TDB + JD2_TDB - START_OF_MJD;
}

