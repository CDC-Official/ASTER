double TCG2TCB(double MJD_TCG,
               const double earth_vx_mps, const double earth_vy_mps, const double earth_vz_mps,
               const double dx_m, const double dy_m, const double dz_m)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Geocentric Coordinate Time (TCG) to Barycentric Coordinate
	 *   Time (TCB) at a user-supplied target position.
	 * - Inputs:
	 *   MJD_TCG is TCG as Modified Julian Date.
	 *   earth_vx_mps, earth_vy_mps, earth_vz_mps are the BCRS velocity
	 *   components of the Earth in meters per second.
	 *   dx_m, dy_m, dz_m are the target position components relative to the
	 *   geocenter, r-r_E, in meters.
	 * - Output:
	 *   The returned value is TCB as Modified Julian Date.
	 * - Formula:
	 *   TCB = TCG + (geocenter_sec + position_sec) / 86400
	 *   where position_sec = v_E dot (r-r_E) / c^2.
	 * - Scope:
	 *   This function assumes Earth velocity and target position are already
	 *   known. It does not call JPL or any other ephemeris reader.
	 */

	// Convert the input TCG epoch to TT because the geocentric HF2002 term is evaluated with a TT/TDB-like JD.
	double JD1_TT, JD2_TT;
	iauTcgtt(START_OF_MJD + MJD_TCG, 0.0, &JD1_TT, &JD2_TT);

	// Geocentric term: TCB-TCG at the Earth's center, in seconds.
	double geocenter_sec = GeocenterTCBMinusTCG_HF2002(JD1_TT + JD2_TT);

	// Position term: first-order correction from geocenter to the target position, in seconds.
	double position_sec = (earth_vx_mps * dx_m + earth_vy_mps * dy_m + earth_vz_mps * dz_m) / (CMPS * CMPS);

	// TCB is ahead of TCG by the total offset. Convert seconds to days before adding to MJD.
	return MJD_TCG + (geocenter_sec + position_sec) / DAYSEC;
}

double TCB2TCG(double MJD_TCB,
               const double earth_vx_mps, const double earth_vy_mps, const double earth_vz_mps,
               const double dx_m, const double dy_m, const double dz_m)
{
	/*
	 * Developer notes:内
	 * - Purpose:
	 *   Convert Barycentric Coordinate Time (TCB) to Geocentric Coordinate
	 *   Time (TCG) at a user-supplied target position.
	 * - Inputs:
	 *   MJD_TCB is TCB as Modified Julian Date.
	 *   earth_vx_mps, earth_vy_mps, earth_vz_mps are the BCRS velocity
	 *   components of the Earth in meters per second.
	 *   dx_m, dy_m, dz_m are the target position components relative to the
	 *   geocenter, r-r_E, in meters.
	 * - Output:
	 *   The returned value is TCG as Modified Julian Date.
	 * - Formula:
	 *   TCG = TCB - (geocenter_sec + position_sec) / 86400
	 *   where position_sec = v_E dot (r-r_E) / c^2.
	 * - Time argument:
	 *   HF2002 is formally evaluated as a function of TDB, so this function
	 *   first converts the input TCB to TDB with SOFA.
	 * - Scope:
	 *   This function assumes Earth velocity and target position are already
	 *   known. It does not call JPL or any other ephemeris reader.
	 */

	// Convert the input TCB epoch to TDB before evaluating the HF2002 geocentric term.
	double JD1_TDB, JD2_TDB;
	iauTcbtdb(START_OF_MJD + MJD_TCB, 0.0, &JD1_TDB, &JD2_TDB);

	// Geocentric term: TCB-TCG at the Earth's center, in seconds.
	double geocenter_sec = GeocenterTCBMinusTCG_HF2002(JD1_TDB + JD2_TDB);

	// Position term: first-order correction from geocenter to the target position, in seconds.
	double position_sec = (earth_vx_mps * dx_m + earth_vy_mps * dy_m + earth_vz_mps * dz_m) / (CMPS * CMPS);

	// TCG is behind TCB by the total offset. Convert seconds to days before subtracting from MJD.
	return MJD_TCB - (geocenter_sec + position_sec) / DAYSEC;
}

double TDB2TT(double MJD_TDB, const double dx_m, const double dy_m, const double dz_m)
{
	/*
	 * Developer notes:
	 * - Purpose:
	 *   Convert Barycentric Dynamical Time (TDB) to Terrestrial Time (TT) for
	 *   a target whose position is expressed in EBCRS.
	 * - Inputs:
	 *   MJD_TDB is the input time in Modified Julian Date.
	 *   dx_m, dy_m, dz_m are the target EBCRS position components in meters.
	 *   In this library EBCRS is BCRS translated to the geocenter, so these
	 *   three values are exactly r-r_E.
	 * - Ephemeris:
	 *   The Earth velocity is read from the already loaded JPL ephemeris with
	 *   Get_JPLEPH(MJD_TDB, 3, 12, ...). In this wrapper, target 3 gives the
	 *   Earth and center 12 gives the solar-system barycenter. Therefore the
	 *   returned velocity is the Earth BCRS velocity.
	 * - Units:
	 *   Get_JPLEPH returns normalized position and velocity. Only the Earth
	 *   velocity is needed here, and it is converted back to m/s before calling
	 *   TCB2TCG.
	 * - Time chain:
	 *   TDB -> TCB is the SOFA linear transformation wrapped by TDB2TCB.
	 *   TCB -> TCG is the HF2002 geocentric TCB-TCG model plus the local
	 *   position correction v_E dot (r-r_E) / c^2.
	 *   TCG -> TT is the SOFA linear transformation wrapped by TCG2TT.
	 * - Requirement:
	 *   Read_JPLEPH must be called before this function, otherwise the JPL
	 *   file handle used by Get_JPLEPH is not ready.
	 */

	double rv_earth_norm[6] = {0.0};

	// Read the Earth's BCRS state from JPL: target 3 is Earth, center 12 is the solar-system barycenter.
	Get_JPLEPH(MJD_TDB, 3, 12, rv_earth_norm);

	// Convert the normalized Earth BCRS velocity to SI units required by TCB2TCG.
	double earth_vx_mps = rv_earth_norm[3] * NORMALIZED_VELOCITY_TO_MPS;
	double earth_vy_mps = rv_earth_norm[4] * NORMALIZED_VELOCITY_TO_MPS;
	double earth_vz_mps = rv_earth_norm[5] * NORMALIZED_VELOCITY_TO_MPS;

	// First convert the barycentric dynamical time to barycentric coordinate time.
	double MJD_TCB = TDB2TCB(MJD_TDB);

	// Then move from TCB to TCG at the target's EBCRS position.
	double MJD_TCG = TCB2TCG(MJD_TCB, earth_vx_mps, earth_vy_mps, earth_vz_mps, dx_m, dy_m, dz_m);

	// Finally convert the geocentric coordinate time to TT.
	return TCG2TT(MJD_TCG);
}
